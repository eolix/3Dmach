"""
The "Max-Style Dark" theme, shipped as a theme preset (``mx_dark.xml``, generated by ``build_theme.py``
from `palette`).

It is never applied silently: the add-on preferences have an "Apply Max-Style Theme" button
(``preferences.mx_apply_theme``) and "Install as Theme Preset" (``preferences.mx_install_theme``), which
copies the XML to the user's theme presets so it shows in Preferences > Themes.
"""

import os
import shutil

import bpy
from bpy.types import Operator

from . import palette  # noqa: F401 (the data behind mx_dark.xml, used by tests and build_theme.py)

THEME_NAME = "Max-Style Dark"
THEME_FILENAME = "mx_dark.xml"
THEME_PATH = os.path.join(os.path.dirname(__file__), THEME_FILENAME)
PRESET_MENU = "USERPREF_MT_interface_theme_presets"
PRESET_FILENAME = "Max-Style_Dark.xml"


def apply_theme(filepath=THEME_PATH):
    """Reset to the default theme and load ``filepath`` (an XML theme preset)."""
    result = bpy.ops.script.execute_preset(filepath=filepath, menu_idname=PRESET_MENU)
    if 'FINISHED' not in result:
        raise RuntimeError("Could not load the theme {!r}".format(filepath))


def installed_preset_path(create=False):
    directory = bpy.utils.user_resource('SCRIPTS', path=os.path.join("presets", "interface_theme"), create=create)
    return os.path.join(directory, PRESET_FILENAME)


class PREFERENCES_OT_mx_apply_theme(Operator):
    """Apply the Max-Style Dark theme (an original dark-gray theme)"""
    bl_idname = "preferences.mx_apply_theme"
    bl_label = "Apply Max-Style Theme"
    bl_options = {'REGISTER'}

    def execute(self, context):
        try:
            apply_theme()
        except RuntimeError as ex:
            self.report({'ERROR'}, str(ex))
            return {'CANCELLED'}
        context.preferences.is_dirty = True
        return {'FINISHED'}


class PREFERENCES_OT_mx_install_theme(Operator):
    """Copy the Max-Style Dark theme to your theme presets (Preferences > Themes)"""
    bl_idname = "preferences.mx_install_theme"
    bl_label = "Install as Theme Preset"
    bl_options = {'REGISTER'}

    def execute(self, _context):
        target = installed_preset_path(create=True)
        shutil.copyfile(THEME_PATH, target)
        self.report({'INFO'}, "Installed {:s}".format(target))
        return {'FINISHED'}


classes = (
    PREFERENCES_OT_mx_apply_theme,
    PREFERENCES_OT_mx_install_theme,
)
