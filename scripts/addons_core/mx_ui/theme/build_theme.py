"""
Developer tool (not imported by the add-on): regenerate ``mx_dark.xml`` from ``palette.py``.

Run with::

    blender -b --factory-startup --python scripts/addons_core/mx_ui/theme/build_theme.py

It resets Blender's theme to the defaults, applies the palette and writes a complete theme preset,
so the XML is coherent with the Blender version it was generated with.
"""

import os
import sys

import bpy

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import palette  # noqa: E402

OUTPUT = os.path.join(HERE, "mx_dark.xml")
HEADER = (
    "<!--\n"
    "SPDX-FileCopyrightText: 2026 PROJECT_NAME Authors\n"
    "\n"
    "SPDX-License-Identifier: GPL-2.0-or-later\n"
    "\n"
    "Max-Style Dark theme. Generated by build_theme.py from palette.py on Blender {version}; do not edit.\n"
    "-->\n"
)


def iter_colors(data, path=""):
    """(path, owner, property identifier) for every colour property below ``data``."""
    for prop in data.bl_rna.properties:
        ident = prop.identifier
        if ident == "rna_type":
            continue
        sub_path = (path + "." + ident) if path else ident
        if prop.type == 'POINTER':
            value = getattr(data, ident)
            if value is not None:
                yield from iter_colors(value, sub_path)
        elif prop.type == 'COLLECTION':
            for index, item in enumerate(getattr(data, ident)):
                yield from iter_colors(item, "{:s}[{:d}]".format(sub_path, index))
        elif prop.type == 'FLOAT' and prop.subtype in {'COLOR', 'COLOR_GAMMA'}:
            yield sub_path, data, ident


def resolve(theme, path):
    owner_path, _, ident = path.rpartition(".")
    owner = theme.path_resolve(owner_path) if owner_path else theme
    if ident not in owner.bl_rna.properties:
        raise KeyError("Theme has no property {!r}".format(path))
    return owner, ident


def build(context):
    bpy.ops.preferences.reset_default_theme()
    theme = context.preferences.themes[0]
    changed = 0
    for path, owner, ident in iter_colors(theme):
        color = tuple(getattr(owner, ident))
        new = palette.adjust_color(path, color)
        if new != color:
            setattr(owner, ident, new)
            changed += 1
    for path, value in palette.OVERRIDES.items():
        owner, ident = resolve(theme, path)
        setattr(owner, ident, value)
    theme.name = "Max-Style Dark"
    return changed


def write(context, filepath):
    import _rna_xml as rna_xml
    menu = bpy.types.USERPREF_MT_interface_theme_presets
    rna_xml.xml_file_write(context, filepath, menu.preset_xml_map)
    with open(filepath, "r", encoding="utf-8") as fh:
        body = fh.read()
    with open(filepath, "w", encoding="utf-8") as fh:
        fh.write(HEADER.format(version=bpy.app.version_string))
        fh.write(body)


def main():
    context = bpy.context
    changed = build(context)
    write(context, OUTPUT)
    bpy.ops.preferences.reset_default_theme()
    print("Wrote {:s} ({:d} lifted colours, {:d} overrides)".format(OUTPUT, changed, len(palette.OVERRIDES)))


if __name__ == "__main__":
    main()
